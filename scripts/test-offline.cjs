const { chromium, devices } = require('playwright');
const OUT = process.argv[2];
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['iPhone 15 Pro'], colorScheme: 'light' });
  const p = await ctx.newPage();
  p.on('pageerror', (e) => console.log('PAGEERROR', e.message));
  await p.route('**/api/calendar*', (r) => r.fulfill({ json: { connected: true, events: [] } }));
  await p.goto('http://localhost:8787/auth/dev');
  await p.waitForSelector('.stats');
  await p.evaluate(() => navigator.serviceWorker.ready);
  await p.reload(); await p.waitForSelector('.stats');
  console.log('online status:', await p.textContent('#sync'));
  await ctx.setOffline(true);
  await p.reload(); await p.waitForSelector('.stats', { timeout: 8000 });
  console.log('offline reload status:', await p.textContent('#sync'));
  await p.click('#fab'); await p.fill('#qa-input', 'Offline Aufgabe heute p1'); await p.keyboard.press('Enter');
  await p.waitForTimeout(300);
  await p.click('#fab'); await p.fill('#qa-input', 'Noch eine offline'); await p.keyboard.press('Enter');
  await p.waitForTimeout(300);
  console.log('queued status:', await p.textContent('#sync'));
  await p.screenshot({ path: OUT + '/offline.png' });
  await ctx.setOffline(false);
  await p.evaluate(() => window.dispatchEvent(new Event('online')));
  await p.waitForTimeout(2500);
  console.log('after sync status:', await p.textContent('#sync'));
  const r = await p.evaluate(() => fetch('/api/tasks').then((r) => r.json()));
  console.log('server tasks:', r.tasks.map((t) => t.title + ' p' + t.priority));
  await p.screenshot({ path: OUT + '/online.png' });
  await b.close();
})();
